#!/usr/bin/env python3
"""Compile a PicoRTK settings file into the firmware as its defaults (private builds only).

    python3 tools/make_defaults.py picortk-config.json      # writes firmware/PicoRTK/defaults_local.h
    bash tools/build.sh                                      # the UF2 now starts with these settings
    python3 tools/make_defaults.py --remove                  # back to the public defaults

The settings file is the one from System -> Backup -> Download settings. The generated header holds
Wi-Fi and caster passwords in plain text: it is git-ignored, never commit it or publish the UF2 built with it.
Saved settings on a Pico still take precedence; System -> Restore defaults switches a Pico to these ones.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "firmware", "PicoRTK", "defaults_local.h")

if len(sys.argv) == 2 and sys.argv[1] == "--remove":
    if os.path.exists(OUT):
        os.remove(OUT)
    print("removed", os.path.normpath(OUT))
    sys.exit(0)
if len(sys.argv) != 2:
    sys.exit(__doc__)

with open(sys.argv[1], encoding="utf-8") as f:
    cfg = json.load(f)
for key in ("wifi", "ntrip"):
    if key not in cfg:
        sys.exit(f"{sys.argv[1]}: no '{key}' section - is this a PicoRTK settings file?")
text = json.dumps(cfg, separators=(",", ":"), ensure_ascii=False)
if ')json"' in text:
    sys.exit("settings contain the sequence )json\" which cannot be embedded")
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/make_defaults.py - PRIVATE: contains passwords. Do not commit.\n#pragma once\n")
    f.write('#define PICORTK_DEFAULT_CONFIG R"json(' + text + ')json"\n')
print("wrote", os.path.normpath(OUT), f"({len(cfg['wifi'])} Wi-Fi networks, {sum(1 for s in cfg['ntrip'] if s.get('host'))} correction sources)")
