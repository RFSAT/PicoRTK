#!/usr/bin/env python3
"""Embed firmware/web/index.html into firmware/PicoRTK/web_page.h (run before every build)."""
import pathlib, re
root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "firmware/web/index.html").read_text(encoding="utf-8")
# Light minification: drop leading indentation and blank lines
html = "\n".join(l.strip() for l in html.splitlines() if l.strip())
assert ')rawliteral"' not in html
out = root / "firmware/PicoRTK/web_page.h"
out.write_text('// Generated by tools/embed_web.py from firmware/web/index.html - do not edit\n#pragma once\n#include <Arduino.h>\n'
               'static const char INDEX_HTML[] PROGMEM = R"rawliteral(' + html + ')rawliteral";\n', encoding="utf-8")
print(f"web_page.h: {len(html)} bytes")
